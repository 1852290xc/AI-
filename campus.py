EARTH_R = 6371.0


def distance_km(lat1, lng1, lat2, lng2):
    if None in (lat1, lng1, lat2, lng2):
        return None
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp = p2 - p1
    dl = math.radians(lng2 - lng1)
    a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * EARTH_R * math.asin(math.sqrt(a))


def coords(name):
    item = CAMPUSES.get(name or "")
    return (item[0], item[1]) if item else None


def nearest_campus(lat, lng):
    best = (None, None)
    for name, (clat, clng, *_rest) in CAMPUSES.items():
        d = distance_km(lat, lng, clat, clng)
        if d is not None and (best[1] is None or d < best[1]):
            best = (name, d)
    return best


def proximity(lat, lng, school, radius_km=15.0):
    if lat is None or lng is None:
        return 0.0, None
    c = coords(school)
    if not c:
        return 0.0, None
    d = distance_km(lat, lng, c[0], c[1])
    if d is None:
        return 0.0, None
    return max(0.0, 1.0 - d / radius_km), d


def all_campuses(lat=None, lng=None):
    """带距离的高校列表；有定位按距离升序，没有则按名称。"""
    rows = []
    for name, (clat, clng, city, region) in CAMPUSES.items():
        d = distance_km(lat, lng, clat, clng) if lat is not None else None
        rows.append({"name": name, "lat": clat, "lng": clng, "city": city,
                     "region": region, "km": round(d, 1) if d is not None else None})
    rows.sort(key=(lambda r: r["km"]) if lat is not None else (lambda r: r["name"]))
    return rows
