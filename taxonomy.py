BY_KEY = {g["key"]: g for g in GROUPS}


def group_categories(key):
    """该大类覆盖的站内分类（用于筛选）。"""
    g = BY_KEY.get(key)
    if not g:
        return []
    cats = []
    for _, cs, _ in g["subs"]:
        for c in cs:
            if c not in cats:
                cats.append(c)
    return cats


def sub_keyword(group_key, sub_name):
    g = BY_KEY.get(group_key)
    if not g:
        return ""
    for name, _, kw in g["subs"]:
        if name == sub_name:
            return kw
    return ""
